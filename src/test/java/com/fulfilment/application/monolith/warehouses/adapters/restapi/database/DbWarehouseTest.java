
package com.fulfilment.application.monolith.warehouses.adapters.restapi.database;

import com.fulfilment.application.monolith.warehouses.adapters.database.DbWarehouse;
import com.fulfilment.application.monolith.warehouses.domain.models.Warehouse;
import org.junit.jupiter.api.Test;

import java.time.LocalDateTime;

import static org.junit.jupiter.api.Assertions.*;

class DbWarehouseTest {

    @Test
    void shouldConvertWarehouseToDbWarehouse() {
        Warehouse warehouse = new Warehouse();
        warehouse.id = 10L;
        warehouse.businessUnitCode = "MWH001";
        warehouse.location = "ZWOLLE-001";
        warehouse.capacity = 100;
        warehouse.stock = 50;
        warehouse.createdAt = LocalDateTime.now();
        warehouse.archivedAt = null;

        DbWarehouse result = DbWarehouse.fromWarehouse(warehouse);

        assertEquals("MWH001", result.businessUnitCode);
        assertEquals("ZWOLLE-001", result.location);
        assertEquals(100, result.capacity);
        assertEquals(50, result.stock);
        assertEquals(warehouse.createdAt, result.createdAt);
        assertNull(result.archivedAt);

        // ID is generated by the database, so it is not copied.
        assertNull(result.id);
    }

    @Test
    void shouldConvertDbWarehouseToWarehouse() {
        DbWarehouse dbWarehouse = new DbWarehouse();
        dbWarehouse.id = 10L;
        dbWarehouse.businessUnitCode = "MWH001";
        dbWarehouse.location = "ZWOLLE-001";
        dbWarehouse.capacity = 100;
        dbWarehouse.stock = 50;
        dbWarehouse.createdAt = LocalDateTime.now();
        dbWarehouse.archivedAt = LocalDateTime.now();

        Warehouse result = dbWarehouse.toWarehouse();

        assertEquals(10L, result.id);
        assertEquals("MWH001", result.businessUnitCode);
        assertEquals("ZWOLLE-001", result.location);
        assertEquals(100, result.capacity);
        assertEquals(50, result.stock);
        assertEquals(dbWarehouse.createdAt, result.createdAt);
        assertEquals(dbWarehouse.archivedAt, result.archivedAt);
    }
}